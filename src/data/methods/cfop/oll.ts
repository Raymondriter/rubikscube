import { caseFromSolution } from '../../algorithm'
import type { AlgorithmCase } from '../../types'

function oll(n: number, name: string, group: string, solution: string): AlgorithmCase {
  return caseFromSolution({
    id: `cfop-oll-${String(n).padStart(2, '0')}`,
    method: 'cfop',
    step: 'cfop-oll',
    name: `OLL ${n} · ${name}`,
    group,
    solution,
    yellowOnU: true,
    recognitionHighlight: ['U', 'UF', 'UR', 'UB', 'UL', 'URF', 'URB', 'ULB', 'ULF'],
    tags: ['cfop', 'oll', group],
  })
}

